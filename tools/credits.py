#!/usr/bin/env python3
"""Write CONTRIBUTORS.md: the authors of the projects whose code wocport contains.

The lists come from GitHub (`gh api repos/<repo>/contributors`); bots are left out. With
--trailers it prints instead the Co-authored-by lines that credit the main authors on a commit
(GitHub shows them as the commit's co-authors), e.g.
    git commit --allow-empty -F <(echo "Credit upstream authors"; echo; tools/credits.py --trailers)
"""
import argparse
import datetime
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# (repository, what wocport has from it, minimum commits for a Co-authored-by trailer)
PROJECTS = [
    ('deadinside28/bloodborne_pc', 'the base of this port: the offline eboot conversion, the loader, '
     'the HLE runtime, the extended shadPS4 renderer, the launcher, the AppImage (its full history '
     'is this repository\'s history)', 1),
    ('Supermedo/bloodborne_pc', 'the Windows port bloodborne_pc grew from; the DLSS bridge and loader', 2),
    ('IFreemz/shadPS4-Bloodborne-DLSS-FSR', 'the DLSS bridge (gpu/dlss_bridge), through Supermedo\'s '
     'port (its authors beyond shadPS4\'s)', 1),
    ('bigmak94/AstroQuest', 'PlayStation VR: libSceHmd with its reprojection and distortion, '
     'libSceVrTracker, libSceCamera, libSceAudio3d, the OpenXR host (SteamVR)', 1),
    ('shadps4-emu/shadPS4', 'the video core, the shader recompiler, common code and the PS4 '
     'libraries listed in gpu/VENDOR.txt', 10),
    ('shadps4-emu/sirit', 'the SPIR-V emitter of the shader recompiler', 20),
    ('aarvsn/Ryty', 'the base of libSceJson2 (gpu/shadps4/core/libraries/json/json2.cpp)', 1),
    ('FireBurn/FSR-Vulkan', 'FSR 3.1 on Vulkan and the FSR 4 v07 provider', 1),
    ('Thealexbarney/LibAtrac9', 'the ATRAC9 decoder', 1),
]
# The port's own authors (the rest of them are in its git history).
PORT = ('The WipEout port: [shipa-2](https://github.com/shipa-2) (Shipa Snake), on the work of '
        'deadinside28 below.')
# Forks of another listed project.
FORKS = {'IFreemz/shadPS4-Bloodborne-DLSS-FSR': 'shadps4-emu/shadPS4'}
# Contributions acknowledged in a project's own credits rather than its commit list.
EXTRA = {
    'bigmak94/AstroQuest': [('ODevStudio', 'SteamVR and Valve Index support, the desktop spectator views')],
}


def contributors(repo):
    out = subprocess.run(['gh', 'api', '--paginate', f'repos/{repo}/contributors?per_page=100',
                          '--jq', '.[] | {login, id, type, contributions}'],
                         capture_output=True, text=True, check=True).stdout
    people = [json.loads(line) for line in out.splitlines() if line.strip()]
    return [p for p in people if p.get('type') != 'Bot' and not p['login'].endswith('[bot]')]


def noreply(person):
    return f'{person["id"]}+{person["login"]}@users.noreply.github.com'


def markdown(lists):
    today = datetime.date.today().isoformat()
    lines = ['# Contributors', '',
             'wocport is built from the work of the people below. The port\'s own authors are in the',
             'git history; the authors of the projects whose code it contains are listed per project',
             f'(from each repository\'s GitHub contributors, {today}; regenerated by `tools/credits.py`).',
             'What each project gave and under which license: [CREDITS.md](CREDITS.md).', '',
             '## wocport', '', PORT, '']
    for (repo, what, _), people in zip(PROJECTS, lists):
        lines += [f'## [{repo}](https://github.com/{repo})', '', what[0].upper() + what[1:] + '.', '']
        for login, note in EXTRA.get(repo, []):
            lines.append(f'Thanks in its credits: [{login}](https://github.com/{login}) — {note}.')
            lines.append('')
        lines.append(', '.join(f'[{p["login"]}](https://github.com/{p["login"]})' for p in people))
        lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--trailers', action='store_true', help='print Co-authored-by lines')
    args = parser.parse_args()
    lists = [contributors(repo) for repo, _, _ in PROJECTS]
    # A fork's list repeats its parent's: keep the fork's own authors.
    by_repo = dict(zip((repo for repo, _, _ in PROJECTS), lists))
    for i, (repo, _, _) in enumerate(PROJECTS):
        parent = FORKS.get(repo)
        if parent:
            known = {p['login'] for p in by_repo[parent]}
            lists[i] = [p for p in lists[i] if p['login'] not in known]
    if args.trailers:
        seen = set()
        for (_, _, minimum), people in zip(PROJECTS, lists):
            for p in people:
                if minimum and p['contributions'] >= minimum and p['login'] not in seen:
                    seen.add(p['login'])
                    print(f'Co-authored-by: {p["login"]} <{noreply(p)}>')
        return
    (ROOT / 'CONTRIBUTORS.md').write_text(markdown(lists), encoding='utf-8')


if __name__ == '__main__':
    main()
